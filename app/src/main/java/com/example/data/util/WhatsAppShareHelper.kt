package com.example.data.util

import android.content.Context
import android.content.Intent
import android.net.Uri
import android.widget.Toast
import com.example.data.model.MemberBalance
import com.example.data.model.MonthlyReportData
import com.example.data.model.SettlementTransaction
import java.net.URLEncoder

object WhatsAppShareHelper {

    /**
     * Builds a comprehensive, well-formatted WhatsApp message summarizing the group expenses and settlement.
     */
    fun buildGroupWhatsAppSummary(report: MonthlyReportData): String {
        val sb = StringBuilder()
        sb.appendLine("🏠 *RoomieSplit • Slovenia Living Expenses*")
        sb.appendLine("📅 *Billing Period:* ${report.periodLabel}")
        sb.appendLine("💶 *Total Expenses:* ${report.totalFormatted} (${report.expenseCount} bills)")
        sb.appendLine("👤 *Average per person:* ${report.averageFormatted}")
        sb.appendLine()

        if (report.categoryBreakdowns.isNotEmpty()) {
            sb.appendLine("📊 *Category Breakdown:*")
            for (cat in report.categoryBreakdowns) {
                val icon = when (cat.category) {
                    "Grocery" -> "🛒"
                    "Room Rent" -> "🏢"
                    "Household Items" -> "🧻"
                    "Bills & Utilities" -> "⚡"
                    "Dining & Takeout" -> "🍕"
                    "Transportation" -> "🚌"
                    else -> "📦"
                }
                sb.appendLine("  $icon ${cat.category}: ${cat.totalFormatted} (${String.format(java.util.Locale.US, "%.1f", cat.percentage)}%)")
            }
            sb.appendLine()
        }

        sb.appendLine("👥 *Participant Balances:*")
        for (b in report.memberBalances) {
            val status = when {
                b.isOwed -> "🟢 Receives ${b.netBalanceFormatted}"
                b.owesMoney -> "🔴 Owes ${b.netBalanceFormatted}"
                else -> "⚪ Settled (€0.00)"
            }
            sb.appendLine("  • *${b.member.name}*: Paid ${b.totalPaidFormatted} | Share ${b.totalShareFormatted} ➡️ $status")
        }
        sb.appendLine()

        sb.appendLine("🤝 *Fair Settlement Plan (Who pays whom):*")
        if (report.settlementPlan.isEmpty()) {
            sb.appendLine("  🎉 *All accounts are completely balanced! No payments needed.*")
        } else {
            report.settlementPlan.forEachIndexed { index, step ->
                sb.appendLine("  ${index + 1}. *${step.fromMember.name}* ➡️ *${step.toMember.name}*: *${step.amountFormatted}*")
            }
        }

        sb.appendLine()
        sb.appendLine("💡 _Generated by RoomieSplit (Slovenia)_")
        return sb.toString()
    }

    /**
     * Builds a personal message for a single member with their dues/receivables.
     */
    fun buildIndividualWhatsAppSummary(
        balance: MemberBalance,
        periodLabel: String,
        settlements: List<SettlementTransaction>
    ): String {
        val sb = StringBuilder()
        sb.appendLine("👋 Hi *${balance.member.name}*, here is your *RoomieSplit* summary:")
        sb.appendLine("📅 *Period:* $periodLabel")
        sb.appendLine("💰 *Your Total Paid:* ${balance.totalPaidFormatted}")
        sb.appendLine("🧾 *Your Share of Bills:* ${balance.totalShareFormatted}")

        when {
            balance.isOwed -> {
                sb.appendLine("🟢 *Net Balance:* You are owed *${balance.netBalanceFormatted}*")
                val debtors = settlements.filter { it.toMember.id == balance.member.id }
                if (debtors.isNotEmpty()) {
                    sb.appendLine("👉 Expected transfers to you:")
                    debtors.forEach {
                        sb.appendLine("  • ${it.fromMember.name} will pay you *${it.amountFormatted}*")
                    }
                }
            }
            balance.owesMoney -> {
                sb.appendLine("🔴 *Net Balance:* You need to pay *${balance.netBalanceFormatted}*")
                val creditors = settlements.filter { it.fromMember.id == balance.member.id }
                if (creditors.isNotEmpty()) {
                    sb.appendLine("👉 Please transfer:")
                    creditors.forEach {
                        sb.appendLine("  • Pay *${it.amountFormatted}* to *${it.toMember.name}*")
                    }
                }
            }
            else -> {
                sb.appendLine("⚪ *Net Balance:* All settled! You owe €0.00.")
            }
        }

        sb.appendLine()
        sb.appendLine("Thanks for keeping our apartment expenses transparent! 🏠🇸🇮")
        return sb.toString()
    }

    /**
     * Builds a comprehensive itemized statement for a specific roommate,
     * including list of bills paid and list of bills shared.
     */
    fun buildDetailedMemberStatement(
        member: com.example.data.model.Member,
        periodLabel: String,
        allExpenses: List<com.example.data.model.Expense>,
        balance: MemberBalance,
        settlements: List<SettlementTransaction>
    ): String {
        val sb = StringBuilder()
        sb.appendLine("🏠 *RoomieSplit Personal Statement • Slovenia*")
        sb.appendLine("👤 *Housemate:* ${member.name} (${if (member.notes.isNotBlank()) member.notes else "Flatmate"})")
        sb.appendLine("📅 *Billing Period:* $periodLabel")
        sb.appendLine("─────────────────────────")
        sb.appendLine("📊 *Financial Summary:*")
        sb.appendLine("  • Total you paid for flat: ${balance.totalPaidFormatted}")
        sb.appendLine("  • Your allocated share: ${balance.totalShareFormatted}")

        val netStatus = when {
            balance.isOwed -> "🟢 *You receive ${balance.netBalanceFormatted}*"
            balance.owesMoney -> "🔴 *You owe ${balance.netBalanceFormatted}*"
            else -> "⚪ *All settled (€0.00)*"
        }
        sb.appendLine("  • Final Net Balance: $netStatus")
        sb.appendLine("─────────────────────────")

        // Bills paid by this person
        val paidBills = allExpenses.filter { it.payerMemberId == member.id }
        if (paidBills.isNotEmpty()) {
            sb.appendLine("🧾 *Bills You Paid (${paidBills.size}):*")
            paidBills.forEach { exp ->
                sb.appendLine("  • ${exp.title}: ${exp.amountFormatted} (${exp.category})")
            }
            sb.appendLine()
        }

        // Bills shared by this person
        val sharedBills = allExpenses.filter { it.getSplitMemberIdList().contains(member.id) }
        if (sharedBills.isNotEmpty()) {
            sb.appendLine("👥 *Bills You Shared In (${sharedBills.size}):*")
            sharedBills.take(8).forEach { exp ->
                val count = exp.getSplitMemberIdList().size
                val perPerson = if (count > 0) exp.amountCents / count else 0L
                val formattedShare = String.format(java.util.Locale.US, "€%.2f", perPerson / 100.0)
                sb.appendLine("  • ${exp.title}: $formattedShare (Total ${exp.amountFormatted} / $count members)")
            }
            if (sharedBills.size > 8) {
                sb.appendLine("  • ... and ${sharedBills.size - 8} more bills")
            }
            sb.appendLine()
        }

        // Settlement instructions
        sb.appendLine("🤝 *Settlement Instructions:*")
        if (balance.isOwed) {
            val debtors = settlements.filter { it.toMember.id == member.id }
            if (debtors.isNotEmpty()) {
                debtors.forEach {
                    sb.appendLine("  👉 *${it.fromMember.name}* will transfer *${it.amountFormatted}* to you")
                }
            } else {
                sb.appendLine("  🎉 No pending transfers to collect.")
            }
        } else if (balance.owesMoney) {
            val creditors = settlements.filter { it.fromMember.id == member.id }
            if (creditors.isNotEmpty()) {
                creditors.forEach {
                    sb.appendLine("  👉 Please transfer *${it.amountFormatted}* to *${it.toMember.name}*")
                }
            }
        } else {
            sb.appendLine("  🎉 Everything is fully settled!")
        }

        sb.appendLine()
        sb.appendLine("💡 _Generated by RoomieSplit App_")
        return sb.toString()
    }

    /**
     * Dispatches intent directly to WhatsApp or falls back to system share sheet.
     */
    fun shareText(context: Context, text: String, phoneNumber: String? = null) {
        try {
            val cleanPhone = phoneNumber?.replace(Regex("[^0-9+]"), "")
            if (!cleanPhone.isNullOrBlank()) {
                val encodedText = URLEncoder.encode(text, "UTF-8")
                val uri = Uri.parse("https://api.whatsapp.com/send?phone=$cleanPhone&text=$encodedText")
                val waIntent = Intent(Intent.ACTION_VIEW, uri)
                waIntent.flags = Intent.FLAG_ACTIVITY_NEW_TASK
                context.startActivity(waIntent)
                return
            }
        } catch (_: Exception) {
            // Fallback to standard share
        }

        // Standard share intent
        try {
            val sendIntent = Intent().apply {
                action = Intent.ACTION_SEND
                putExtra(Intent.EXTRA_TEXT, text)
                type = "text/plain"
            }
            val shareIntent = Intent.createChooser(sendIntent, "Share RoomieSplit via WhatsApp")
            shareIntent.flags = Intent.FLAG_ACTIVITY_NEW_TASK
            context.startActivity(shareIntent)
        } catch (e: Exception) {
            Toast.makeText(context, "Could not open share dialog: ${e.message}", Toast.LENGTH_SHORT).show()
        }
    }
}
